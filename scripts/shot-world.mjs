/** Quick look at the walkable world. BASE_URL=http://localhost:3100 node scripts/shot-world.mjs [phone] */
import { mkdirSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(new URL("../e2e/", import.meta.url));
const { chromium } = require("@playwright/test");
const BASE = process.env.BASE_URL ?? "http://localhost:3100";
mkdirSync(".screenshots", { recursive: true });
const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const phone = process.argv[2] === "phone";
const ctx = await browser.newContext({ viewport: phone ? { width: 390, height: 844 } : { width: 1440, height: 900 }, hasTouch: phone });
const page = await ctx.newPage();
page.on("console", (m) => ["error", "warning"].includes(m.type()) && console.log(`console ${m.type()}: ${m.text().slice(0, 300)}`));
page.on("pageerror", (e) => console.log(`pageerror: ${e.message}`));
const tag = phone ? "p" : "d";
await page.goto(BASE);
await page.waitForSelector("canvas[data-stage=ready]", { timeout: 60000 });
await page.waitForTimeout(9000);
await page.screenshot({ path: `.screenshots/w-${tag}-1-start.png` });
await page.getByRole("button", { name: "Start exploring" }).click();
await page.keyboard.down("ArrowUp");
await page.waitForTimeout(3500);
await page.keyboard.up("ArrowUp");
await page.waitForTimeout(800);
await page.screenshot({ path: `.screenshots/w-${tag}-2-walked.png` });
await page.keyboard.down("KeyE");
await page.waitForTimeout(1500);
await page.keyboard.up("KeyE");
await page.screenshot({ path: `.screenshots/w-${tag}-3-turned.png` });
await page.getByRole("button", { name: "All towers" }).click();
await page.locator("[data-room=agents]").click();
await page.waitForSelector("textarea", { timeout: 20000 });
await page.waitForTimeout(6000);
await page.screenshot({ path: `.screenshots/w-${tag}-4-room.png` });
await browser.close();
console.log("done");
